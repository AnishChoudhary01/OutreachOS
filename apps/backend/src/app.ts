import express from 'express';
import cors from 'cors';
import { emailRouter } from './routes/emails.js';
import { authRouter } from './routes/auth.js';
import { loadSession, requireSameOrigin } from './middleware/auth.js';
import { searchRouter } from './routes/search.js';
import { env } from './config/env.js';
import { createBullBoard } from '@bull-board/api';
import { BullMQAdapter } from '@bull-board/api/bullMQAdapter';
import { ExpressAdapter } from '@bull-board/express';
import { emailQueue } from './queues/emailQueue.js';
import { requireAdmin } from './middleware/auth.js';
import { senderRouter } from './routes/senders.js';
export const app = express(); app.use(cors({ origin: env.FRONTEND_ORIGIN, credentials: true })); app.use(express.json({ limit: '2mb' })); app.use(loadSession); app.use(requireSameOrigin);
const boardAdapter = new ExpressAdapter(); boardAdapter.setBasePath('/admin/queues'); createBullBoard({ queues: [new BullMQAdapter(emailQueue)], serverAdapter: boardAdapter });
app.get('/api/health', (_req, res) => res.json({ status: 'ok', service: 'outreachos-api' })); app.use('/api/auth', authRouter); app.use('/api/emails', emailRouter); app.use('/api/search', searchRouter); app.use('/api/senders', senderRouter); app.use('/admin/queues', requireAdmin, boardAdapter.getRouter());
app.use((err: any, _req: express.Request, res: express.Response, _next: express.NextFunction) => { if (err?.name === 'ZodError') return res.status(400).json({ error: 'Validation failed', details: err.issues }); const status = err?.statusCode || 500; return res.status(status).json({ error: status === 500 ? 'Internal server error' : err.message }); });
